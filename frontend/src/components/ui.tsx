export function Select({ value, onChange, options, placeholder, label: l }: { value: string; onChange: (v: string) => void; options: (string | { value: string; label: string })[]; placeholder?: string; label: string }) {
  return (
    <select aria-label={l} className="input !w-auto" value={value} onChange={(e) => onChange(e.target.value)}>
      {placeholder !== undefined && <option value="">{placeholder}</option>}
      {options.map((o) => { const v = typeof o === 'string' ? o : o.value; const t = typeof o === 'string' ? label(o) : o.label; return <option key={v} value={v}>{t}</option> })}
    </select>
  )
}
export function Toggle({ checked, onChange, disabled, title, name }: { checked: boolean; onChange: (v: boolean) => void; disabled?: boolean; title?: string; name: string }) {
  return (
    <button role="switch" aria-checked={checked} aria-label={name} title={title} disabled={disabled} onClick={() => onChange(!checked)}
      className={`relative h-6 w-11 rounded-full transition disabled:cursor-not-allowed disabled:opacity-50 ${checked ? 'bg-teal-600' : 'bg-slate-300 dark:bg-slate-700'}`}>
      <span className={`absolute top-0.5 h-5 w-5 rounded-full bg-white transition ${checked ? 'left-[22px]' : 'left-0.5'}`} />
    </button>
  )
}
export function ListToArr(s: string): string[] { return s.split(',').map((x) => x.trim()).filter(Boolean) }
export function useDebounced<T>(v: T, ms = 300): T {
  const [s, set] = useState(v)
  useEffect(() => { const t = setTimeout(() => set(v), ms); return () => clearTimeout(t) }, [v, ms])
  return s
}
